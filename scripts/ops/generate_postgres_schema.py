"""Generate ``app/storage/schema_postgres.sql`` from the current SQLite schema.

The SQLite schema (``app/storage/db.py`` migrations) stays the source of truth. This
script builds a fresh SQLite database at the latest version, reads every table
and index back from ``sqlite_master`` and translates them to PostgreSQL. The
parts SQLite expresses differently are written by hand below: the full-text
table (FTS5 there, ``tsvector`` + GIN here), the triggers that keep it in sync,
the pgvector column, and a few SQLite functions the queries call.

    uv run --locked python scripts/ops/generate_postgres_schema.py          # rewrite
    uv run --locked python scripts/ops/generate_postgres_schema.py --check  # CI parity

``tests/test_postgres_schema.py`` runs the check, so a SQLite migration that is
not mirrored here fails the build instead of drifting silently.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from contextlib import closing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
TARGET = ROOT / "app" / "storage" / "schema_postgres.sql"

#: SQLite internals and the FTS5 virtual table (replaced by ``FTS_SQL``).
SKIPPED_TABLES = re.compile(r"^(sqlite_|pages_fts)")
TYPES = {"INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION", "BLOB": "BYTEA", "TEXT": "TEXT"}

HEADER = """\
-- Generated by scripts/ops/generate_postgres_schema.py from SQLite schema version {version}.
-- Do not edit by hand: change the SQLite migration, then regenerate.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS lexvault_schema_meta (
    singleton BIGINT PRIMARY KEY CHECK (singleton = 1),
    version BIGINT NOT NULL
);

-- SQLite functions that application SQL calls directly.
CREATE OR REPLACE FUNCTION datetime(value TEXT, modifier TEXT) RETURNS TEXT
    LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT to_char(CASE WHEN modifier = 'localtime' THEN localtimestamp ELSE now() AT TIME ZONE 'UTC' END,
                   'YYYY-MM-DD HH24:MI:SS')
    WHERE value = 'now'
$$;
"""

#: FTS5 ranks document_name, doc_type and text with weights 1.6 / 1.2 / 1.0;
#: the tsvector keeps the same columns in weight classes A / B / C.
FTS_SQL = """
CREATE TABLE IF NOT EXISTS pages_fts (
    page_id BIGINT PRIMARY KEY,
    case_id BIGINT,
    document_id BIGINT,
    page_no BIGINT,
    document_name TEXT,
    doc_type TEXT,
    text TEXT,
    tsv tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('simple', coalesce(document_name, '')), 'A') ||
        setweight(to_tsvector('simple', coalesce(doc_type, '')), 'B') ||
        setweight(to_tsvector('simple', coalesce(text, '')), 'C')
    ) STORED
);
CREATE INDEX IF NOT EXISTS pages_fts_tsv ON pages_fts USING gin (tsv);
CREATE INDEX IF NOT EXISTS pages_fts_case ON pages_fts (case_id);

CREATE OR REPLACE FUNCTION lexvault_pages_fts_sync() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        DELETE FROM pages_fts WHERE page_id = OLD.id;
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        INSERT INTO pages_fts(page_id, case_id, document_id, page_no, document_name, doc_type, text)
        SELECT NEW.id, d.case_id, NEW.document_id, NEW.page_no, d.name, d.doc_type, NEW.text
        FROM documents d WHERE d.id = NEW.document_id;
    END IF;
    RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS pages_fts_sync ON pages;
CREATE TRIGGER pages_fts_sync AFTER INSERT OR UPDATE OR DELETE ON pages
    FOR EACH ROW EXECUTE FUNCTION lexvault_pages_fts_sync();

CREATE OR REPLACE FUNCTION lexvault_documents_fts_sync() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE pages_fts SET document_name = NEW.name, doc_type = NEW.doc_type, case_id = NEW.case_id
    WHERE document_id = NEW.id;
    RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS documents_fts_update ON documents;
CREATE TRIGGER documents_fts_update AFTER UPDATE OF name, doc_type, case_id ON documents
    FOR EACH ROW EXECUTE FUNCTION lexvault_documents_fts_sync();

CREATE OR REPLACE FUNCTION lexvault_host_runtime_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO host_runtime_cleanup VALUES (OLD.framework_run_id, OLD.request_id) ON CONFLICT DO NOTHING;
    RETURN OLD;
END $$;
DROP TRIGGER IF EXISTS host_runtime_delete ON host_runtime_links;
CREATE TRIGGER host_runtime_delete BEFORE DELETE ON host_runtime_links
    FOR EACH ROW EXECUTE FUNCTION lexvault_host_runtime_delete();

-- Page vectors: the JSON text stays the source of truth (SQLite reads it);
-- PostgreSQL derives a pgvector value from it so similarity runs in the database.
ALTER TABLE embedding_cache ADD COLUMN IF NOT EXISTS embedding vector
    GENERATED ALWAYS AS (CASE WHEN vector_json IN ('', '[]') THEN NULL ELSE vector_json::vector END) STORED;
"""

#: Row-level security for information walls. A walled case's rows are visible
#: only to its insiders, to holders of an active break-glass grant, and to
#: system connections (startup, workers, index rebuilds). Administrators are not
#: exempt. The same policy shape keyed on a tenant id is multi-tenant isolation.
WALL_FUNCTION = """
-- Walled cases hidden from the current connection's identity. Policies wrap the
-- call in a scalar subquery, so it runs once per statement, not once per row.
CREATE OR REPLACE FUNCTION lexvault_hidden_cases() RETURNS bigint[]
    LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT CASE WHEN coalesce(current_setting('lexvault.system', true), '') = 'on' THEN '{}'::bigint[]
           ELSE coalesce(array_agg(w.case_id), '{}'::bigint[]) END
    FROM case_walls w
    WHERE NOT EXISTS (SELECT 1 FROM case_wall_insiders i
                      WHERE i.case_id = w.case_id AND i.principal_name = current_setting('lexvault.actor', true))
      AND NOT EXISTS (SELECT 1 FROM case_wall_grants g
                      WHERE g.case_id = w.case_id AND g.principal_name = current_setting('lexvault.actor', true)
                        AND g.expires_at > extract(epoch FROM now()))
$$;
DROP FUNCTION IF EXISTS lexvault_case_visible(BIGINT);
"""
#: Tables that hold case material directly (their own ``case_id``).
WALLED_DIRECT = (
    "agent_runs", "bank_transactions", "batch_dispatch", "batch_imports", "case_parties", "case_reports",
    "chat_requests", "conflict_checks",
    "conversations", "documents", "evidence", "evidence_relations", "gap_detections", "host_write_receipts",
    "llm_calls", "memories", "pages_fts", "rag_evaluations", "review_jobs", "review_tasks", "runtime_requests",
)
#: Tables that reach their case through a parent row: (column, parent table).
WALLED_VIA = {
    "agent_steps": ("run_id", "agent_runs"),
    "bank_transaction_relations": ("evidence_id", "evidence"),
    "batch_import_files": ("batch_id", "batch_imports"),
    "case_report_events": ("report_id", "case_reports"),
    "case_report_versions": ("report_id", "case_reports"),
    "embedding_cache": ("page_id", "pages"),
    "evidence_annotations": ("evidence_id", "evidence"),
    "host_runtime_links": ("conversation_id", "conversations"),
    "messages": ("conversation_id", "conversations"),
    "page_child_chunks": ("page_id", "pages"),
    "page_child_index_state": ("page_id", "pages"),
    "pages": ("document_id", "documents"),
    "review_task_events": ("task_id", "review_tasks"),
}
#: Case-linked tables that deliberately stay visible, and why.
WALL_EXEMPT = {
    "audit_log": "compliance trail: the firm's auditors see every record",
    "security_events": "security trail, no case material",
    "case_members": "membership resolves identities before a request has a principal",
    "case_walls": "the wall itself", "case_wall_insiders": "the wall itself", "case_wall_grants": "the wall itself",
}
CASE_LINK_COLUMNS = ("case_id", "document_id", "page_id", "conversation_id", "run_id", "evidence_id",
                     "report_id", "task_id", "batch_id")


def wall_policies(columns: dict[str, list[str]]) -> str:
    unclassified = sorted(
        name for name, cols in columns.items()
        if name != "cases" and any(col in CASE_LINK_COLUMNS for col in cols)
        and name not in WALLED_DIRECT and name not in WALLED_VIA and name not in WALL_EXEMPT)
    if unclassified:
        raise SystemExit(f"case-linked tables without a wall rule: {', '.join(unclassified)}")
    # The cast makes ANY take the array, not treat the subquery as a row set.
    hidden = "(SELECT lexvault_hidden_cases())::bigint[]"
    rules = {"cases": f"NOT (id = ANY ({hidden}))"}
    rules.update({name: f"case_id IS NULL OR NOT (case_id = ANY ({hidden}))" for name in WALLED_DIRECT})
    for name, (column, parent) in WALLED_VIA.items():
        # Nothing hidden: true without touching the parent. Otherwise a
        # primary-key probe of the parent row, whose own policy applies; the
        # cost follows the rows a query touches, not the size of the parent.
        rules[name] = (f"cardinality({hidden}) = 0 OR {column} IS NULL "
                       f"OR EXISTS (SELECT 1 FROM {parent} p WHERE p.id = {name}.{column})")
    parts = [WALL_FUNCTION]
    for name in sorted(rules):
        parts.append(
            f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY;\n"
            f"ALTER TABLE {name} FORCE ROW LEVEL SECURITY;\n"
            f"DROP POLICY IF EXISTS lexvault_wall ON {name};\n"
            f"CREATE POLICY lexvault_wall ON {name} USING ({rules[name]});"
        )
    return "\n".join(parts)


#: Triggers written by hand above; any other SQLite trigger must be ported.
PORTED_TRIGGERS = {"documents_fts_update", "host_runtime_delete", "pages_fts_delete",
                   "pages_fts_insert", "pages_fts_update"}


def sqlite_schema() -> tuple[int, list[tuple[str, str, str, str]]]:
    with tempfile.TemporaryDirectory(prefix="lexvault-schema-") as directory:
        os.environ.setdefault("LAW_REVIEW_DATA_DIR", directory)
        from app.storage.db import SCHEMA_VERSION, connect, db_scope, init_db

        with db_scope(Path(directory) / "law_review.db"):
            init_db(seed=False)
            with closing(connect()) as conn:
                rows = [tuple(row) for row in conn.execute(
                    "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY name")]
    return SCHEMA_VERSION, rows


def _split_columns(body: str) -> list[str]:
    parts, depth, current, quote = [], 0, [], ""
    for char in body:
        if quote:
            current.append(char)
            if char == quote:
                quote = ""
            continue
        if char in "'\"":
            quote = char
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
            continue
        current.append(char)
    if "".join(current).strip():
        parts.append("".join(current).strip())
    return parts


def translate_column(definition: str) -> str:
    match = re.match(r"(\w+)\s+(INTEGER|REAL|BLOB|TEXT)\b(.*)$", definition, re.S)
    if not match:
        return definition  # table constraint: UNIQUE(...), CHECK (...), FOREIGN KEY ...
    name, kind, rest = match.groups()
    if name == "id" and kind == "INTEGER" and re.match(r"\s*PRIMARY KEY\b", rest):
        rest = re.sub(r"\s*PRIMARY KEY(\s+AUTOINCREMENT)?", "", rest, count=1)
        return f"{name} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY{rest}"
    rest = re.sub(r"\s+AUTOINCREMENT\b", "", rest)
    return f"{name} {TYPES[kind]}{rest}"


def translate_table(sql: str) -> tuple[str, set[str]]:
    head, body = sql.split("(", 1)
    body = body.rsplit(")", 1)[0]
    name = head.split()[-1].strip("'\"")
    columns = [translate_column(part) for part in _split_columns(body)]
    references = set(re.findall(r"REFERENCES\s+(\w+)", body)) - {name}
    lines = ",\n    ".join(columns)
    return f"CREATE TABLE IF NOT EXISTS {name} (\n    {lines}\n);", references


def translate_index(sql: str) -> str:
    return re.sub(r"^CREATE (UNIQUE )?INDEX ", r"CREATE \1INDEX IF NOT EXISTS ", sql.strip()) + ";"


def render() -> str:
    version, rows = sqlite_schema()
    tables: dict[str, tuple[str, set[str]]] = {}
    columns: dict[str, list[str]] = {"pages_fts": ["case_id", "document_id", "page_id"]}
    indexes: list[str] = []
    for kind, name, table, sql in rows:
        if kind == "table" and not SKIPPED_TABLES.match(name):
            tables[name] = translate_table(sql)
            body = sql.split("(", 1)[1].rsplit(")", 1)[0]
            columns[name] = [part.split()[0].strip('"') for part in _split_columns(body) if part.split()]
        elif kind == "index" and not SKIPPED_TABLES.match(table):
            indexes.append(translate_index(sql))
        elif kind == "trigger" and name not in PORTED_TRIGGERS:
            raise SystemExit(f"SQLite trigger {name} has no PostgreSQL port; add it to FTS_SQL")
    ordered: list[str] = []

    def visit(name: str, path: tuple[str, ...] = ()) -> None:
        if name in ordered:
            return
        if name in path:
            raise SystemExit(f"foreign-key cycle: {' -> '.join(path + (name,))}")
        for dependency in sorted(tables[name][1]):
            visit(dependency, path + (name,))
        ordered.append(name)

    for name in sorted(tables):
        visit(name)
    parts = [HEADER.format(version=version)]
    parts += [tables[name][0] for name in ordered]
    parts.append("")
    parts += indexes
    parts.append(FTS_SQL)
    parts.append(wall_policies(columns))
    return "\n".join(parts).rstrip() + "\n"


def missing_migrations() -> list[str]:
    """Every schema version after the migration baseline needs its upgrade step."""
    from app.storage.db import SCHEMA_VERSION
    from app.storage.db_postgres import MIGRATION_BASELINE, migration_file

    return [migration_file(version).relative_to(ROOT).as_posix()
            for version in range(MIGRATION_BASELINE + 1, SCHEMA_VERSION + 1) if not migration_file(version).exists()]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)
    text = render()
    missing = missing_migrations()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("app/storage/schema_postgres.sql 与当前 SQLite 结构不一致；运行 scripts/ops/generate_postgres_schema.py", file=sys.stderr)
            return 1
    else:
        TARGET.write_text(text, encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)}")
    if missing:
        print("缺少 PostgreSQL 迁移：" + "、".join(missing) + "（每个新版本都要有升级步骤，见 docs/runbook/postgresql.md）",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
