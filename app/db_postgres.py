"""PostgreSQL behind the sqlite3-shaped connection the application already uses.

The application talks to its database through ``app.db.connect()`` and the
sqlite3 DB-API subset: ``execute`` with ``?`` placeholders, ``lastrowid``,
rows readable by index and by column name, ``with conn:`` committing, and
``sqlite3.IntegrityError`` for constraint violations. ``PgConnection`` keeps
that contract on PostgreSQL so the same queries run on both backends:

* ``?`` placeholders become ``%s``; a literal ``%`` is escaped.
* ``INSERT`` into a table with an identity ``id`` gets ``RETURNING id`` so
  ``lastrowid`` works; an insert that sets ``id`` explicitly moves the
  sequence past it, as SQLite's rowid allocation would.
* ``INSERT OR IGNORE`` becomes ``ON CONFLICT DO NOTHING``.
* ``BEGIN IMMEDIATE`` (SQLite's single-writer lock, taken before
  read-check-write sequences) becomes a transaction-scoped advisory lock, so
  those sections stay serialized across connections and processes.
* Every statement runs inside a savepoint: a failed statement leaves the
  transaction usable, as in SQLite, instead of aborting it.
* The few PRAGMAs the application issues are answered from PostgreSQL's
  catalogue; ``user_version`` lives in ``lexvault_schema_meta``.
* Result values keep SQLite's Python types: integers stay ``int`` even when
  PostgreSQL computes ``numeric`` (``SUM``), comparisons stay ``0``/``1``.
* Booleans are written as ``0``/``1``; NUL characters, which PostgreSQL
  ``TEXT`` cannot store, are dropped from text parameters.

Features that copy the SQLite *file* (snapshots, the isolated framework
sidecar, LangGraph's checkpoint store) keep using SQLite files; see
``docs/runbook/postgresql.md``.
"""
from __future__ import annotations

import re
import sqlite3
from collections.abc import Iterator, Sequence
from dataclasses import dataclass
from decimal import Decimal
from functools import lru_cache
from pathlib import Path
from typing import Any

import psycopg
from psycopg import errors as pg_errors
from psycopg.pq import TransactionStatus

SCHEMA_FILE = Path(__file__).with_name("schema_postgres.sql")
#: Key of the advisory lock that stands in for SQLite's RESERVED lock.
WRITER_LOCK_KEY = 0x4C455856  # "LEXV"


class Row:
    """Read by index or by column name, like ``sqlite3.Row``."""

    __slots__ = ("_index", "_values")

    def __init__(self, values: tuple[Any, ...], index: dict[str, int]) -> None:
        self._values = values
        self._index = index

    def __getitem__(self, key: int | str | slice) -> Any:
        if isinstance(key, str):
            return self._values[self._index[key]]
        return self._values[key]

    def keys(self) -> list[str]:
        return list(self._index)

    def __iter__(self) -> Iterator[Any]:
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def __eq__(self, other: object) -> bool:
        if isinstance(other, Row):
            return self._values == other._values and self.keys() == other.keys()
        return NotImplemented

    def __hash__(self) -> int:
        return hash(self._values)

    def __repr__(self) -> str:
        return f"Row({dict(zip(self.keys(), self._values, strict=False))!r})"


def _python_value(value: Any) -> Any:
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, Decimal):
        return int(value) if value == value.to_integral_value() else float(value)
    return value


def _row_factory(cursor: Any):
    names = [column.name for column in cursor.description or ()]
    index: dict[str, int] = {}
    for position, name in enumerate(names):
        index.setdefault(name, position)  # sqlite3.Row returns the first duplicate

    def make(values: Sequence[Any]) -> Row:
        return Row(tuple(_python_value(value) for value in values), index)

    return make


@lru_cache(maxsize=1)
def identity_tables() -> frozenset[str]:
    """Tables whose ``id`` is an identity column (SQLite ``INTEGER PRIMARY KEY``)."""
    text = SCHEMA_FILE.read_text(encoding="utf-8")
    return frozenset(re.findall(
        r"CREATE TABLE IF NOT EXISTS (\w+) \(\s*id BIGINT GENERATED BY DEFAULT AS IDENTITY", text))


@dataclass(frozen=True)
class Statement:
    text: str
    kind: str = "query"            # query | noop | writer_lock | pragma
    returning_id: bool = False
    sync_identity: str | None = None
    pragma: tuple[str, str | None] | None = None


_INSERT = re.compile(r"^\s*INSERT\s+(?:OR\s+(\w+)\s+)?INTO\s+(\w+)\s*(\(([^)]*)\))?", re.I | re.S)
_PRAGMA = re.compile(r"^\s*PRAGMA\s+(\w+)\s*(?:=\s*(\S+?)|\(\s*'?(\w+)'?\s*\))?\s*;?\s*$", re.I)


def _placeholders(sql: str) -> str:
    """``?`` outside literals becomes ``%s``; every ``%`` is escaped for psycopg."""
    out: list[str] = []
    quote = ""
    for char in sql:
        if char == "%":
            out.append("%%")
            continue
        if quote:
            if char == quote:
                quote = ""
            out.append(char)
            continue
        if char in "'\"":
            quote = char
            out.append(char)
        elif char == "?":
            out.append("%s")
        else:
            out.append(char)
    return "".join(out)


@lru_cache(maxsize=4096)
def translate(sql: str) -> Statement:
    stripped = sql.strip().rstrip(";").strip()
    upper = stripped.upper()
    if upper in {"BEGIN", "BEGIN TRANSACTION", "BEGIN DEFERRED"}:
        return Statement("", kind="noop")
    if upper in {"BEGIN IMMEDIATE", "BEGIN EXCLUSIVE"}:
        return Statement("SELECT pg_advisory_xact_lock(%s)", kind="writer_lock")
    pragma = _PRAGMA.match(stripped)
    if pragma:
        name, value, argument = pragma.groups()
        return Statement("", kind="pragma", pragma=(name.lower(), value or argument))
    text = stripped
    returning_id = False
    sync_identity = None
    insert = _INSERT.match(text)
    if insert:
        conflict, table, _, columns = insert.groups()
        if conflict:
            if conflict.upper() != "IGNORE":
                raise NotImplementedError(f"INSERT OR {conflict} has no generic PostgreSQL form; write an upsert")
            text = re.sub(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", text, count=1, flags=re.I)
            returning = re.search(r"\bRETURNING\b", text, re.I)
            if returning:
                text = text[:returning.start()] + "ON CONFLICT DO NOTHING " + text[returning.start():]
            else:
                text += " ON CONFLICT DO NOTHING"
        if table in identity_tables():
            explicit = columns is None or "id" in {part.strip().strip('"') for part in columns.split(",")}
            if explicit:
                sync_identity = table
            if not re.search(r"\bRETURNING\b", text, re.I):
                text += " RETURNING id"
                returning_id = True
    return Statement(_placeholders(text), returning_id=returning_id, sync_identity=sync_identity)


def _adapt_value(value: Any) -> Any:
    if isinstance(value, bool):
        return int(value)  # columns are INTEGER 0/1, as in SQLite
    if isinstance(value, str) and "\x00" in value:
        # PostgreSQL TEXT cannot hold NUL; SQLite stores it. NUL never carries
        # meaning in case text, so it is dropped instead of failing the write.
        return value.replace("\x00", "")
    return value


def _adapt(params: Any) -> Any:
    if params is None:
        return ()
    if isinstance(params, dict):
        raise NotImplementedError("named parameters are not used by the application")
    return tuple(_adapt_value(value) for value in params)


def _translate_error(exc: psycopg.Error) -> sqlite3.Error:
    message = str(exc).strip().splitlines()[0] if str(exc).strip() else type(exc).__name__
    if isinstance(exc, psycopg.IntegrityError):
        return sqlite3.IntegrityError(message)
    if isinstance(exc, pg_errors.UndefinedTable | pg_errors.UndefinedColumn | pg_errors.UndefinedFunction
                  | pg_errors.SyntaxError | pg_errors.QueryCanceled | pg_errors.LockNotAvailable):
        return sqlite3.OperationalError(message)
    return sqlite3.DatabaseError(message)


class Cursor:
    """The part of ``sqlite3.Cursor`` the application reads."""

    def __init__(self, cursor: Any = None, *, lastrowid: int | None = None, consumed: bool = False,
                 rows: list[Row] | None = None, rowcount: int = -1) -> None:
        self._cursor = cursor
        self._rows = rows
        self._consumed = consumed
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount if cursor is not None else rowcount
        self.description = cursor.description if cursor is not None and not consumed else None

    def fetchone(self) -> Row | None:
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        if self._consumed or self._cursor is None or self._cursor.description is None:
            return None
        return self._cursor.fetchone()

    def fetchall(self) -> list[Row]:
        if self._rows is not None:
            rows, self._rows = self._rows, []
            return rows
        if self._consumed or self._cursor is None or self._cursor.description is None:
            return []
        return self._cursor.fetchall()

    def fetchmany(self, size: int = 1) -> list[Row]:
        return [row for row in (self.fetchone() for _ in range(size)) if row is not None]

    def __iter__(self) -> Iterator[Row]:
        while (row := self.fetchone()) is not None:
            yield row


#: Connections opened by this process; the test suite uses it to report how
#: many tests actually reached PostgreSQL.
connections_opened = 0


class PgConnection:
    """One PostgreSQL connection with the sqlite3 connection surface the app uses."""

    def __init__(self, url: str) -> None:
        global connections_opened
        connections_opened += 1
        try:
            self._conn = psycopg.connect(url, autocommit=False, row_factory=_row_factory)
        except psycopg.OperationalError as exc:
            raise sqlite3.OperationalError(f"PostgreSQL unavailable: {type(exc).__name__}") from exc
        self.row_factory = None  # accepted and ignored: rows are always Row objects

    # -- statements --------------------------------------------------------
    def execute(self, sql: str, params: Any = ()) -> Cursor:
        statement = translate(sql)
        if statement.kind == "noop":
            return Cursor(rowcount=-1)
        if statement.kind == "pragma":
            return self._pragma(*statement.pragma)  # type: ignore[misc]
        if statement.kind == "writer_lock":
            return self._run(statement.text, (WRITER_LOCK_KEY,), consume=True)
        cursor = self._run(statement.text, _adapt(params), consume=statement.returning_id,
                           returning_id=statement.returning_id)
        if statement.sync_identity:
            self._run(
                f"SELECT setval(pg_get_serial_sequence('{statement.sync_identity}', 'id'), "
                f"GREATEST((SELECT COALESCE(MAX(id), 0) FROM {statement.sync_identity}), 1))", (), consume=True)
        return cursor

    def executemany(self, sql: str, seq_of_params: Any) -> Cursor:
        total = 0
        last: Cursor | None = None
        for params in seq_of_params:
            last = self.execute(sql, params)
            total += max(last.rowcount, 0)
        return Cursor(rowcount=total, lastrowid=last.lastrowid if last else None)

    def executescript(self, script: str) -> Cursor:
        # Several statements in one call need the simple query protocol: no parameters.
        try:
            self._conn.execute(script.encode("utf-8"))
        except psycopg.Error as exc:
            raise _translate_error(exc) from exc
        return Cursor(rowcount=-1)

    def _run(self, text: str, params: tuple[Any, ...], *, consume: bool, returning_id: bool = False) -> Cursor:
        # The savepoint commands use their own cursors: the statement's cursor
        # keeps its client-side result set for the caller.
        cursor = self._conn.cursor()
        try:
            self._conn.execute("SAVEPOINT lexvault_statement")
            cursor.execute(text, params)
            rows = cursor.fetchall() if consume and cursor.description is not None else None
            self._conn.execute("RELEASE SAVEPOINT lexvault_statement")
        except psycopg.Error as exc:
            if self._conn.info.transaction_status == TransactionStatus.INERROR:
                self._conn.execute("ROLLBACK TO SAVEPOINT lexvault_statement")
                self._conn.execute("RELEASE SAVEPOINT lexvault_statement")
            raise _translate_error(exc) from exc
        if consume:
            lastrowid = int(rows[-1][0]) if returning_id and rows else None
            return Cursor(cursor, lastrowid=lastrowid, consumed=True)
        return Cursor(cursor)

    def _pragma(self, name: str, argument: str | None) -> Cursor:
        if name in {"foreign_keys", "journal_mode", "busy_timeout", "synchronous", "query_only"}:
            return Cursor(rowcount=-1)
        if name == "user_version":
            if argument is not None:
                self._run("INSERT INTO lexvault_schema_meta(singleton, version) VALUES (1, %s) "
                          "ON CONFLICT (singleton) DO UPDATE SET version = excluded.version",
                          (int(argument),), consume=True)
                return Cursor(rowcount=1)
            cursor = self._run("SELECT COALESCE((SELECT version FROM lexvault_schema_meta), 0) AS user_version",
                               (), consume=False)
            return cursor
        if name == "table_info" and argument:
            return self._run(
                "SELECT ordinal_position - 1 AS cid, column_name AS name, data_type AS type, "
                "CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull, column_default AS dflt_value, 0 AS pk "
                "FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = %s "
                "ORDER BY ordinal_position", (argument,), consume=False)
        if name == "integrity_check":
            return Cursor(rows=[Row(("ok",), {"integrity_check": 0})])
        if name == "foreign_key_check":
            return Cursor(rows=[])
        raise NotImplementedError(f"PRAGMA {name} has no PostgreSQL equivalent here")

    def identify(self, actor: str, system: bool) -> None:
        """Name who is asking, for the row-level security policies.

        Committed at once: a later rollback must not silently reset the
        connection to an anonymous session.
        """
        self._run("SELECT set_config('lexvault.actor', %s, false), set_config('lexvault.system', %s, false)",
                  (actor, "on" if system else "off"), consume=True)
        self._conn.commit()

    # -- transaction and lifetime -----------------------------------------
    @property
    def in_transaction(self) -> bool:
        return self._conn.info.transaction_status != TransactionStatus.IDLE

    def commit(self) -> None:
        try:
            self._conn.commit()
        except psycopg.Error as exc:
            raise _translate_error(exc) from exc

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()

    def __enter__(self) -> PgConnection:
        return self

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> None:
        if exc_type is None:
            self.commit()
        else:
            self.rollback()


